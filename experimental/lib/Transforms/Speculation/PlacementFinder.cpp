PlacementFinder::PlacementFinder(SpeculationPlacements &placements)
    : placements(placements) {
  OpOperand &specPos = placements.getSpeculatorPlacement();
  assert(specPos.getOwner() && "Speculator position is undefined");
}

//===----------------------------------------------------------------------===//
// Save Units Finder Methods
//===----------------------------------------------------------------------===//

// Recursively traverse the IR until reaching branches and store visited values
// The values are stored in the set specValues that is passed by reference
static void markSpeculativePathsForSaves(Operation *currOp,
                                         DenseSet<Value> &specValues) {
  // End traversal when reaching a branch, because save units are only
  // placed inside the speculation BB
  if (isa<handshake::ConditionalBranchOp>(currOp))
    return;

  for (OpResult res : currOp->getResults()) {
    if (specValues.contains(res))
      continue;
    specValues.insert(res);
    for (Operation *succOp : res.getUsers()) {
      markSpeculativePathsForSaves(succOp, specValues);
    }
  }
}

/// Returns whether the value is derived exclusively from source operations,
/// even indirectly. For example, in a circuit like `source -> constant ->
/// trunci`, the result of `trunci` is also considered to be generated by the
/// source.
static bool isGeneratedBySourceOp(Value value) {
  Operation *defOp = value.getDefiningOp();
  // If the value is not produced by any operation, it cannot be considered
  // generated by the source.
  if (!defOp)
    return false;

  if (isa<handshake::SourceOp>(defOp))
    return true;

  // an init starts a control network, which is not fed by a source
  if (isa<handshake::InitOp>(defOp))
    return false;

  // All upstream values must be generated by source operations.
  return llvm::all_of(defOp->getOpOperands(), [&](OpOperand &operand) {
    return isGeneratedBySourceOp(operand.get());
  });
}

// Save units are needed where speculative tokens can interact with
// non-speculative tokens. Updates `placements` with the Save placements
LogicalResult PlacementFinder::findSaves() {
  OpOperand &specPos = placements.getSpeculatorPlacement();
  handshake::FuncOp funcOp =
      specPos.getOwner()->getParentOfType<handshake::FuncOp>();
  assert(funcOp && "op should have parent function");
  auto handshakeBlocks = getLogicBBs(funcOp);

  // Mark all values that are speculative in the speculation BB
  llvm::DenseSet<Value> specValues;
  specValues.insert(specPos.get());
  markSpeculativePathsForSaves(specPos.getOwner(), specValues);

  // Iterate all operations in the speculation BB
  std::optional<unsigned> specBB = getLogicBB(specPos.getOwner());
  if (!specBB) {
    specPos.getOwner()->emitError("Operation does not have a BB.");
    return failure();
  }

  for (Operation *blockOp : handshakeBlocks.blocks[specBB.value()]) {
    // Create a save if an operation has both spec and non-spec operands
    bool hasNonSpecInput = false;
    bool hasSpecInput = false;
    for (Value operand : blockOp->getOperands()) {
      if (specValues.contains(operand))
        hasSpecInput = true;
      else
        hasNonSpecInput = true;
    }

    if (hasSpecInput && hasNonSpecInput) {
      for (OpOperand &operand : blockOp->getOpOperands()) {
        // Create a Save for every non-speculative operand
        if (!specValues.contains(operand.get())) {
          // No save unit required for a value generated by a source operation.
          if (isGeneratedBySourceOp(operand.get()))
            continue;

          placements.addSave(operand);
        }
      }
    }
  }

  return success();
}

//===----------------------------------------------------------------------===//
// Commit Units Finder Methods
//===----------------------------------------------------------------------===//

/// Returns operands to traverse next when placing Commit or SaveCommit.
/// For LoadOps, only data result uses are included. For StoreOp, no targets.
/// For others, all result uses.
static llvm::SmallVector<OpOperand *>
getSpecRegionTraversalTargets(Operation *op) {
  llvm::SmallVector<OpOperand *> targets;
  if (auto loadOp = dyn_cast<handshake::LoadOp>(op)) {
    // Continue traversal only the data result of the LoadOp, skipping results
    // connected to the memory controller.
    for (OpOperand &dstOpOperand : loadOp.getDataResult().getUses()) {
      targets.push_back(&dstOpOperand);
    }
  } else if (isa<handshake::StoreOp>(op)) {
    // Traversal ends here; edges to the memory controller are skipped
    return {};
  } else {
    for (OpResult res : op->getResults()) {
      for (OpOperand &dstOpOperand : res.getUses()) {
        targets.push_back(&dstOpOperand);
      }
    }
  }
  return targets;
}

LogicalResult PlacementFinder::findRegularCommitsTraversal(
    llvm::DenseSet<Operation *> &visited, OpOperand &currOpOperand) {
  Operation *currOp = currOpOperand.getOwner();

  // All save units inside the speculative region should already be converted to
  // save-commits.
  if (placements.containsSave(currOpOperand)) {
    currOp->emitError("Save units should not be reached");
    return failure();
  }

  if (isa<handshake::StoreOp>(currOp) ||
      isa<handshake::MemoryControllerOp>(currOp) ||
      isa<handshake::EndOp>(currOp) || isa<handshake::InitOp>(currOp)) {
    // A Commit is needed in front of these units
    placements.addCommit(currOpOperand);
    // Stop traversal.
    return success();
  }

  auto [_, isNewOp] = visited.insert(currOp);

  // End traversal if currOp is already in visited set
  if (!isNewOp)
    return success();

  for (OpOperand *target : getSpecRegionTraversalTargets(currOp)) {
    // Stop further traversal if Commit, SaveCommit, or Speculator is
    // encountered.
    if (placements.containsCommit(*target) ||
        placements.containsSaveCommit(*target) ||
        &placements.getSpeculatorPlacement() == target)
      continue;

    if (failed(findRegularCommitsTraversal(visited, *target)))
      return failure();
  }

  return success();
}

LogicalResult PlacementFinder::findRegularCommits() {
  OpOperand &specPos = placements.getSpeculatorPlacement();

  // Share visited set with multiple traversals
  llvm::DenseSet<Operation *> visited;

  // Perform the traversal from the speculator position
  if (failed(findRegularCommitsTraversal(visited, specPos)))
    return failure();

  // Perform the same traversal from the save-commit unit positions.
  for (OpOperand *scPos : placements.getPlacements<SpecSaveCommitOp>()) {
    if (failed(findRegularCommitsTraversal(visited, *scPos)))
      return failure();
  }
  return success();
}

namespace {
using CFGEdge = OpOperand;
}

// DFS traversal to mark all operations that lead to Commit units
// The set markedPaths is passed by reference and is updated with
// the OpPlacements (pair value-operation) that are traversed
static void
markSpeculativePathsForCommits(Operation *currOp,
                               SpeculationPlacements &placements,
                               llvm::DenseSet<CFGEdge *> &markedEdges) {
  for (OpOperand *edge : getSpecRegionTraversalTargets(currOp)) {
    if (!markedEdges.count(edge)) {
      markedEdges.insert(edge);
      // Stop traversal if a commit is reached
      if (!placements.containsCommit(*edge))
        markSpeculativePathsForCommits(edge->getOwner(), placements,
                                       markedEdges);
    }
  }
}

// Mark the edges of the speculative region:
// from an op in the region, the region continues downstream along
// every result and upstream along every operand,
// except at the ops below, and ends at commits
static void markSpeculativeRegion(OpOperand &edge, bool isDownstream,
                                  SpeculationPlacements &placements,
                                  llvm::DenseSet<CFGEdge *> &speculativeEdges,
                                  llvm::DenseSet<Operation *> &visited) {
  speculativeEdges.insert(&edge);

  // the region ends at a commit: its input is speculative, its output is not
  if (placements.containsCommit(edge))
    return;

  // the op on the other side of the edge
  Operation *op = isDownstream ? edge.getOwner() : edge.get().getDefiningOp();
  if (!op)
    return;
  if (!visited.insert(op).second)
    return;

  // speculative tokens reaching memory or the end
  // have a commit in front of them
  if (isa<handshake::StoreOp, handshake::MemoryOpInterface, handshake::EndOp>(
          op))
    return;

  // a load: downstream to its data result, upstream to its address
  if (auto loadOp = dyn_cast<handshake::LoadOp>(op)) {
    if (isDownstream) {
      for (OpOperand &use : loadOp.getDataResult().getUses())
        markSpeculativeRegion(use, true, placements, speculativeEdges,
                              visited);
    } else {
      markSpeculativeRegion(loadOp->getOpOperand(0), false, placements,
                            speculativeEdges, visited);
    }
    return;
  }

  // downstream along every result
  for (OpResult res : op->getResults())
    for (OpOperand &use : res.getUses())
      markSpeculativeRegion(use, true, placements, speculativeEdges, visited);

  // a merge or control merge: downstream only
  if (isa<handshake::MergeOp, handshake::ControlMergeOp>(op))
    return;

  // a mux: upstream only to its select
  if (auto muxOp = dyn_cast<handshake::MuxOp>(op)) {
    markSpeculativeRegion(muxOp->getOpOperand(0), false, placements,
                          speculativeEdges, visited);
    return;
  }

  // any other op: upstream along every operand
  for (OpOperand &operand : op->getOpOperands())
    markSpeculativeRegion(operand, false, placements, speculativeEdges,
                          visited);
}

// Mark every edge of the speculative region
static llvm::DenseSet<CFGEdge *>
markSpeculativeRegionEdges(SpeculationPlacements &placements) {
  llvm::DenseSet<CFGEdge *> speculativeEdges;
  llvm::DenseSet<Operation *> visited;

  // the region starts at the speculator's output
  OpOperand &specPos = placements.getSpeculatorPlacement();
  markSpeculativeRegion(specPos, true, placements, speculativeEdges, visited);

  return speculativeEdges;
}

// Mark every edge that a speculative token can travel along:
// the edges reachable from the speculator and from the save-commits,
// up to the commits that stop them
static llvm::DenseSet<CFGEdge *>
markSpeculativeEdges(SpeculationPlacements &placements) {
  llvm::DenseSet<CFGEdge *> speculativeEdges;

  // speculative tokens start on the speculator's edge
  OpOperand &specPos = placements.getSpeculatorPlacement();
  speculativeEdges.insert(&specPos);
  markSpeculativePathsForCommits(specPos.getOwner(), placements,
                                 speculativeEdges);

  // and on each save-commit's edge
  for (OpOperand *scPos : placements.getPlacements<SpecSaveCommitOp>()) {
    // a save-commit with a commit on the same edge
    // sends everything straight into that commit,
    // so nothing speculative starts there
    if (placements.containsCommit(*scPos))
      continue;

    speculativeEdges.insert(scPos);
    markSpeculativePathsForCommits(scPos->getOwner(), placements,
                                   speculativeEdges);
  }

  return speculativeEdges;
}

/// Whether a merge input is the backedge of an innermost loop:
/// it comes out of a cfg branch in the merge's own block,
/// on the side whose successor in the original cfg is that block
static bool isInnermostLoopBackedge(OpOperand &input, Operation *mergeOp) {
  auto condBrOp = input.get().getDefiningOp<handshake::ConditionalBranchOp>();
  if (!condBrOp)
    return false;
  handshake::CfgSuccsAttr succs = condBrOp.getCfgSuccsAttr();
  if (!succs)
    return false;

  // the merge's block, and the original successor on this side
  unsigned mergeBB = getLogicBB(mergeOp).value();
  unsigned sideSucc = input.get() == condBrOp.getTrueResult()
                          ? succs.getTrueSucc()
                          : succs.getFalseSucc();

  return getLogicBB(condBrOp) == mergeBB && sideSucc == mergeBB;
}

// Find the placements of Commit units in front of merges
// that are needed to avoid two speculative tokens going out of order:
// a merge, control merge or mux taking speculative tokens
// from two or more inputs. Updates the `placements`
LogicalResult PlacementFinder::findCommitsBetweenBBs() {
  OpOperand &specPos = placements.getSpeculatorPlacement();
  auto funcOp = specPos.getOwner()->getParentOfType<handshake::FuncOp>();
  assert(funcOp && "op should have parent function");

  // mark every edge that a speculative token can travel along
  llvm::DenseSet<CFGEdge *> speculativeEdges =
      markSpeculativeEdges(placements);

  for (Operation &op : funcOp.getOps()) {
    // the inputs a merge-like op chooses between:
    // every input of a merge or control merge,
    // and the data inputs of a mux
    SmallVector<OpOperand *> mergedInputs;
    if (isa<handshake::MergeOp, handshake::ControlMergeOp>(op)) {
      for (OpOperand &operand : op.getOpOperands())
        mergedInputs.push_back(&operand);
    } else if (auto muxOp = dyn_cast<handshake::MuxOp>(op)) {
      for (OpOperand &operand : muxOp.getDataOperandsMutable())
        mergedInputs.push_back(&operand);
    } else {
      continue;
    }

    // the speculative ones among them
    SmallVector<OpOperand *> specInputs;
    for (OpOperand *input : mergedInputs)
      if (speculativeEdges.contains(input))
        specInputs.push_back(input);

    // one speculative input cannot be reordered
    if (specInputs.size() < 2)
      continue;

    // potential ordering issue, add commits on the speculative inputs
    for (OpOperand *input : specInputs) {
      if (isInnermostLoopBackedge(*input, &op)) {
        llvm::errs() << "Warning: Skipped placing commit units on the "
                        "backedge of the innermost loop to preserve "
                        "speculation. Safe only if the loop's II is 1.\n";
        continue;
      }
      placements.addCommit(*input);
      // Here, synchronizer operations will be needed in the future
    }
  }

  return success();
}

// Fixes an invalid spec region by placing commits.
//
// If a speculative token ends up in a basic block
// that doesn't execute once per execution
// of the speculator's basic block,
// it may join with tokens that do not pass through
// the basic block of the speculator.
// These cannot be co-speculated using a save-commit,
// and so we must stop the speculative token with a commit
// before the invalid join happens
LogicalResult PlacementFinder::findCommitsAtJoins() {
  OpOperand &specPos = placements.getSpeculatorPlacement();
  auto funcOp = specPos.getOwner()->getParentOfType<handshake::FuncOp>();
  assert(funcOp && "op should have parent function");

  bool changed = true;
  while (changed) {
    changed = false;

    // mark every edge that a speculative token can travel along
    llvm::DenseSet<CFGEdge *> speculativeEdges =
        markSpeculativeEdges(placements);

    // an edge with a commit carries the commit's resolved tokens
    for (OpOperand *commitPos :
         placements.getPlacements<handshake::SpecCommitOp>())
      speculativeEdges.erase(commitPos);

    for (Operation &op : funcOp.getOps()) {
      // merges, control merges and muxes
      // only combine tokens from one routing call
      if (isa<handshake::MergeOp, handshake::ControlMergeOp,
              handshake::MuxOp>(op))
        continue;

      // a load's memory data input is the answer to its own address
      if (isa<handshake::LoadOp>(op))
        continue;

      // sort the operands into spec and non-spec
      SmallVector<OpOperand *> specOperands;
      bool hasNonSpecOperand = false;
      for (OpOperand &operand : op.getOpOperands()) {
        // a spec token travels along a marked edge
        if (speculativeEdges.contains(&operand)) {
          specOperands.push_back(&operand);
          continue;
        }

        // a token generated by a source is always available,
        // so a join cannot use it up
        if (isGeneratedBySourceOp(operand.get()))
          continue;

        hasNonSpecOperand = true;
      }

      // a join of spec and non-spec tokens
      // needs commits on its spec operands
      if (specOperands.empty() || !hasNonSpecOperand)
        continue;
      for (OpOperand *operand : specOperands) {
        placements.addCommit(*operand);
        changed = true;
      }
    }
  }

  return success();
}

// Now that all commits have been placed, some of the earlier ones
// might be unreachable: later commits stop the speculative tokens
// before they get there. Hence, the paths to commits are marked again
// and unreachable commits are removed
LogicalResult PlacementFinder::removeUnreachableCommits() {
  // mark every edge of the speculative region,
  // including the edges with commits
  llvm::DenseSet<CFGEdge *> speculativeEdges =
      markSpeculativeRegionEdges(placements);

  // remove commits that cannot be reached
  llvm::DenseSet<CFGEdge *> toRemove;
  for (CFGEdge *edge : placements.getPlacements<handshake::SpecCommitOp>()) {
    if (!speculativeEdges.contains(edge))
      toRemove.insert(edge);
  }
  for (CFGEdge *edge : toRemove)
    placements.eraseCommit(*edge);

  return success();
}

//===----------------------------------------------------------------------===//
// SaveCommit Units Finder Methods
//===----------------------------------------------------------------------===//

// Traverse the speculator's BB from top to bottom (from the control merge
// until the branches) and adds save-commits in such a way that every path is
// cut by a save-commit or the speculator itself. Updates `placements`.
LogicalResult
PlacementFinder::findSaveCommitsTraversal(llvm::DenseSet<Operation *> &visited,
                                          Operation *currOp) {
  // End traversal if currOp is already in visited set
  if (auto [_, isNewOp] = visited.insert(currOp); !isNewOp)
    return success();

  for (OpOperand *target : getSpecRegionTraversalTargets(currOp)) {
    if (placements.containsSave(*target)) {
      // Convert save units in the loop to save-commits
      placements.addSaveCommit(*target);
      placements.eraseSave(*target);
      // The path is cut by the save-commit and stop traversal
      continue;
    }

    // End traversal if the path is already cut by another save-commit
    if (placements.containsSaveCommit(*target))
      continue;

    // End traversal if the path is already cut by the speculator
    OpOperand &specPos = placements.getSpeculatorPlacement();
    if (target == &specPos)
      continue;

    Operation *succOp = target->getOwner();
    if (isa<handshake::ConditionalBranchOp>(succOp)) {
      // A SaveCommit is needed in front of the branch
      placements.addSaveCommit(*target);
      // End traversal
      continue;
    }

    // Continue DFS traversal along the path
    if (failed(findSaveCommitsTraversal(visited, succOp)))
      return failure();
  }
  return success();
}

LogicalResult PlacementFinder::findSaveCommits() {
  OpOperand &specPos = placements.getSpeculatorPlacement();
  auto funcOp = specPos.getOwner()->getParentOfType<handshake::FuncOp>();
  assert(funcOp && "op should have parent function");

  std::optional<unsigned> specBB = getLogicBB(specPos.getOwner());
  if (!specBB) {
    specPos.getOwner()->emitError("Operation does not have a BB.");
    return failure();
  }

  // Each network in the speculation BB starts at a control merge,
  // or at a merge for a network that needs no index (such as the
  // allocation network of a memory interface)
  llvm::DenseSet<Operation *> visited;
  for (Operation &op : funcOp.getOps()) {
    if (!isa<handshake::ControlMergeOp, handshake::MergeOp>(op))
      continue;
    if (getLogicBB(&op) != specBB)
      continue;

    // Add save-commits so that all paths are cut by a save-commit or the
    // speculator
    if (failed(findSaveCommitsTraversal(visited, &op)))
      return failure();
  }

  return success();
}

LogicalResult PlacementFinder::findPlacements() {
  if (failed(findSaves()))
    return failure();

  if (failed(findSaveCommits()))
    return failure();

  // Find commits after save-commit placement is finalized
  if (failed(findRegularCommits()))
    return failure();
  if (failed(findCommitsAtJoins()))
    return failure();
  // after the other commits, which can make merge inputs non-speculative
  if (failed(findCommitsBetweenBBs()))
    return failure();
  if (failed(removeUnreachableCommits()))
    return failure();

  return success();
}
