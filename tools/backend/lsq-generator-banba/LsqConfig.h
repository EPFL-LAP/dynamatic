#ifndef DYNAMATIC_TOOLS_BACKEND_LSQ_GENERATOR_BANBA_LSQCONFIG_H
#define DYNAMATIC_TOOLS_BACKEND_LSQ_GENERATOR_BANBA_LSQCONFIG_H

#include "llvm/Support/JSON.h"
#include <string>
#include <vector>

/// The parameters of an LSQ,
/// as Dynamatic writes them to the LSQ's JSON config file.
/// Each field is named after its key in that file.
struct LsqConfig {
  // Identity
  std::string name;
  bool master;

  // Widths
  unsigned dataWidth;
  unsigned addrWidth;
  unsigned indexWidth;

  // Depths
  unsigned fifoDepth;
  unsigned fifoDepth_L;
  unsigned fifoDepth_S;
  unsigned bufferDepth;

  // Counts
  unsigned numBBs;
  unsigned numLoadPorts;
  unsigned numStorePorts;
  unsigned numLdChannels;
  unsigned numStChannels;
  std::vector<unsigned> numLoads;
  std::vector<unsigned> numStores;

  // Order of the accesses within each group
  std::vector<std::vector<unsigned>> loadOffsets;
  std::vector<std::vector<unsigned>> storeOffsets;
  std::vector<std::vector<unsigned>> loadPorts;
  std::vector<std::vector<unsigned>> storePorts;
  std::vector<std::vector<unsigned>> ldOrder;
  std::vector<std::vector<unsigned>> ldPortIdx;
  std::vector<std::vector<unsigned>> stPortIdx;

  // Switches of the pre-existing LSQ generators
  unsigned stResp;
  unsigned groupMulti;
  unsigned pipe0En;
  unsigned pipe1En;
  unsigned pipeCompEn;
  unsigned headLagEn;
  unsigned bypassEn;

  // Whether the LSQ is to be generated by Banba
  bool BANBA;
};

/// Reads an LSQ's parameters from the parsed content of its JSON config file.
/// `fromJSON` is the name LLVM's JSON library looks for.
bool fromJSON(const llvm::json::Value &value, LsqConfig &config,
              llvm::json::Path path);

/// Checks what Banba requires of the config,
/// and reports the first key that does not satisfy it:
/// the switches of the pre-existing LSQ generators, and `BANBA`,
/// must have the one value Banba supports for them,
/// and there must be at least one load port and one store port.
bool hasRequiredValues(const LsqConfig &config);

#endif // DYNAMATIC_TOOLS_BACKEND_LSQ_GENERATOR_BANBA_LSQCONFIG_H
