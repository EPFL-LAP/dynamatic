#include "LsqConfig.h"
#include "llvm/Support/raw_ostream.h"

bool fromJSON(const llvm::json::Value &value, LsqConfig &config,
              llvm::json::Path path) {
  llvm::json::ObjectMapper mapper(value, path);
  // clang-format off
  return mapper &&
         // Identity
         mapper.map("name", config.name) &&
         mapper.map("master", config.master) &&
         // Widths
         mapper.map("dataWidth", config.dataWidth) &&
         mapper.map("addrWidth", config.addrWidth) &&
         mapper.map("indexWidth", config.indexWidth) &&
         // Depths
         mapper.map("fifoDepth", config.fifoDepth) &&
         mapper.map("fifoDepth_L", config.fifoDepth_L) &&
         mapper.map("fifoDepth_S", config.fifoDepth_S) &&
         mapper.map("bufferDepth", config.bufferDepth) &&
         // Counts
         mapper.map("numBBs", config.numBBs) &&
         mapper.map("numLoadPorts", config.numLoadPorts) &&
         mapper.map("numStorePorts", config.numStorePorts) &&
         mapper.map("numLdChannels", config.numLdChannels) &&
         mapper.map("numStChannels", config.numStChannels) &&
         mapper.map("numLoads", config.numLoads) &&
         mapper.map("numStores", config.numStores) &&
         // Order of the accesses within each group
         mapper.map("loadOffsets", config.loadOffsets) &&
         mapper.map("storeOffsets", config.storeOffsets) &&
         mapper.map("loadPorts", config.loadPorts) &&
         mapper.map("storePorts", config.storePorts) &&
         mapper.map("ldOrder", config.ldOrder) &&
         mapper.map("ldPortIdx", config.ldPortIdx) &&
         mapper.map("stPortIdx", config.stPortIdx) &&
         // Switches of the pre-existing LSQ generators
         mapper.map("stResp", config.stResp) &&
         mapper.map("groupMulti", config.groupMulti) &&
         mapper.map("pipe0En", config.pipe0En) &&
         mapper.map("pipe1En", config.pipe1En) &&
         mapper.map("pipeCompEn", config.pipeCompEn) &&
         mapper.map("headLagEn", config.headLagEn) &&
         mapper.map("bypassEn", config.bypassEn) &&
         // Whether the LSQ is to be generated by Banba
         mapper.map("BANBA", config.BANBA);
  // clang-format on
}

/// Checks that a key has the only value Banba supports for it, and reports
/// the key otherwise.
static bool hasRequiredValue(llvm::StringRef key, unsigned value,
                             unsigned required) {
  if (value == required)
    return true;
  llvm::errs() << "LSQ config: Banba requires '" << key << "' to be "
               << required << ", but it is " << value << "\n";
  return false;
}

bool hasRequiredValues(const LsqConfig &config) {
  // clang-format off
  return hasRequiredValue("bufferDepth", config.bufferDepth, 0) &&
         hasRequiredValue("stResp", config.stResp, 0) &&
         hasRequiredValue("groupMulti", config.groupMulti, 0) &&
         hasRequiredValue("pipe0En", config.pipe0En, 0) &&
         hasRequiredValue("pipe1En", config.pipe1En, 0) &&
         hasRequiredValue("pipeCompEn", config.pipeCompEn, 0) &&
         hasRequiredValue("headLagEn", config.headLagEn, 0) &&
         hasRequiredValue("bypassEn", config.bypassEn, 1);
  // clang-format on
}
